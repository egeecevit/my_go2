// Pins every scalar of templateKin against CrossBarPendulum.kin at two states.
void test_template_kin() {
  std::cout << "test_template_kin..." << std::endl;
  MdlAMB::params_t p;
  const double tol = 1e-9;
  for (const ref_case_t& c : REF) {
    MdlAMB::kin_t k;
    MdlAMB::templateKin(p, Eigen::Vector3d(c.x), Eigen::Vector3d(c.xd), k);
    double worst = 0.0;
    for (int i = 0; i < 3; i++) {
      for (int j = 0; j < 3; j++)
        worst = std::max(worst, std::abs(k.Mt(i, j) - c.Mt[3 * i + j]));
      worst = std::max(worst, std::abs(k.Ct(i) - c.Ct[i]));
      worst = std::max(worst, std::abs(k.Gt(i) - c.Gt[i]));
      worst = std::max(worst, std::abs(k.dcx(i) - c.dcx[i]));
      worst = std::max(worst, std::abs(k.dcy(i) - c.dcy[i]));
    }
    worst = std::max(worst, std::abs(k.cx - c.cx));
    worst = std::max(worst, std::abs(k.cy - c.cy));
    worst = std::max(worst, std::abs(k.cx_bias - c.cx_bias));
    worst = std::max(worst, std::abs(k.cy_bias - c.cy_bias));
    worst = std::max(worst, std::abs(k.m_tot - c.m_tot));
    std::cout << "  " << c.name << ": max |delta| = " << worst << std::endl;
    if (worst >= tol) {
      std::cerr << "  FAIL " << c.name << ": templateKin deviates from Python by "
                << worst << std::endl;
      std::exit(1);
    }
  }
  std::cout << "  PASS" << std::endl;
}

// Pins ambLaw against TemplateController.step(..., momentum_override).
void test_amb_law() {
  std::cout << "test_amb_law..." << std::endl;
  MdlAMB::params_t p;
  for (const ref_case_t& c : REF) {
    MdlAMB::kin_t k;
    Eigen::Vector3d x(c.x), xd(c.xd), xdd;
    MdlAMB::templateKin(p, x, xd, k);
    T_CHECK(MdlAMB::ambLaw(p, k, x, xd, c.L, c.Ld, c.Ldd, c.tau_hat, c.x3d, xdd));
    double worst = 0.0;
    for (int i = 0; i < 3; i++) worst = std::max(worst, std::abs(xdd(i) - c.xdd[i]));
    std::cout << "  " << c.name << ": max |delta xdd| = " << worst << std::endl;
    if (worst >= 1e-8) {
      std::cerr << "  FAIL " << c.name << ": ambLaw deviates from Python by " << worst
                << std::endl;
      std::exit(1);
    }
  }
  std::cout << "  PASS" << std::endl;
}

// Nominal diagonal posture, body frame: stance feet on the centreline, swing
// feet lifted beside their abduction anchors (plan "Nominal posture").
const Eigen::Vector3d FOOT_NOM[4] = {{0.15, 0.0, -0.278},
                                     {0.2634, -0.142, -0.18},
                                     {-0.2634, 0.142, -0.18},
                                     {-0.15, 0.0, -0.278}};

void nominal_posture(const QuadrupedKinematics& kin, Eigen::Vector3d q[4]) {
  for (int leg = 0; leg < 4; leg++) T_CHECK(kin.inverseKinematics(leg, FOOT_NOM[leg], q[leg]));
}

void test_nominal_ik() {
  std::cout << "test_nominal_ik..." << std::endl;
  QuadrupedKinematics kin(createGo2Config());
  Eigen::Vector3d q[4];
  nominal_posture(kin, q);
  const Eigen::Vector3d expected[4] = {{-0.5114, 1.0505, -1.7859},
                                       {0.0, 0.7294, -2.2099},
                                       {0.0, 1.4712, -2.2099},
                                       {-0.5114, 0.7260, -1.7859}};
  for (int leg = 0; leg < 4; leg++) {
    for (int j = 0; j < 3; j++) {
      double err = std::abs(q[leg](j) - expected[leg](j));
      if (err > 1.0 * DEG) {
        std::cerr << "  FAIL leg " << leg << " joint " << j << ": expected "
                  << expected[leg](j) << " got " << q[leg](j) << std::endl;
        std::exit(1);
      }
    }
  }
  std::cout << "  PASS" << std::endl;
}

void nominal_input(MdlAMB::input_t& in) {
  QuadrupedKinematics kin(createGo2Config());
  nominal_posture(kin, in.q);
  for (int leg = 0; leg < 4; leg++) in.qd[leg].setZero();
  in.R.setIdentity();
  in.w_body.setZero();
  in.t = 0.0;
}

void test_project_nominal() {
  std::cout << "test_project_nominal..." << std::endl;
  MdlAMB::params_t p;
  QuadrupedLegDynamics dyn(createGo2DynamicsConfig());
  T_CHECK(dyn.isValid());
  MdlAMB::input_t in;
  nominal_input(in);
  MdlAMB::proj_t pr;
  T_CHECK(MdlAMB::project(p, in, dyn, pr));
  std::cout << "  theta = (" << pr.theta(0) / DEG << ", " << pr.theta(1) / DEG << ", "
            << pr.theta(2) / DEG << ") deg, x3 = " << (pr.theta(1) - pr.theta(2)) / DEG
            << " deg, c_h = " << pr.c_h << " m, l_c = " << pr.l_c << " m, mass = " << pr.mass
            << " kg" << std::endl;
  T_CHECK(std::abs(pr.theta(0)) < 0.5 * DEG);
  T_CHECK(std::abs(pr.theta(1) + 152.0 * DEG) < 0.5 * DEG);
  T_CHECK(std::abs(pr.theta(2) - 152.0 * DEG) < 0.5 * DEG);
  T_CHECK(std::abs(pr.theta(1) - pr.theta(2) + 304.0 * DEG) < 1.0 * DEG);
  // s runs from FL to RR, so it is -x and the in-plane horizontal is +y.
  T_CHECK((pr.s - Eigen::Vector3d(-1, 0, 0)).norm() < 1e-9);
  T_CHECK((pr.th - Eigen::Vector3d(0, 1, 0)).norm() < 1e-9);
  // At rest the finite-difference rates must vanish exactly.
  T_CHECK(pr.thetad.norm() == 0.0 && pr.ch_dot == 0.0 && pr.lc_dot == 0.0);
  std::cout << "  PASS" << std::endl;
}

void test_fd_jacobians() {
  std::cout << "test_fd_jacobians..." << std::endl;
  MdlAMB::params_t p;
  QuadrupedLegDynamics dyn(createGo2DynamicsConfig());
  MdlAMB::input_t in;
  nominal_input(in);
  MdlAMB::proj_t pr;
  T_CHECK(MdlAMB::project(p, in, dyn, pr));

  // Rolling the body by eps about the support line through the base: theta1
  // follows with a slope just under 1 because the sphere rolls and the contact
  // midpoint shifts by r eps along t_h (1 - r / l_b with r = 0.022 m).
  const double eps = 1e-6;
  MdlAMB::input_t rolled = in;
  rolled.R = Eigen::AngleAxisd(eps, pr.s).toRotationMatrix();
  MdlAMB::proj_t pr2;
  T_CHECK(MdlAMB::project(p, rolled, dyn, pr2));
  const double dth1 = (pr2.theta(0) - pr.theta(0)) / eps;
  std::cout << "  j_c = " << pr.j_c << ", j_d = " << pr.j_d
            << ", d theta1 / d roll(s) = " << dth1 << std::endl;
  T_CHECK(std::abs(pr.j_c - 1.0) < 0.02);
  T_CHECK(std::abs(pr.j_d + 1.0) < 0.02);
  T_CHECK(dth1 > 0.9 && dth1 < 1.0);
  std::cout << "  PASS" << std::endl;
}

void test_stance_forces() {
  std::cout << "test_stance_forces..." << std::endl;
  // Stance line at z = 0 along -x, CoM 0.01 m ahead of the midpoint, 0.3 m up.
  MdlAMB::proj_t pr;
  pr.s = Eigen::Vector3d(-1, 0, 0);
  pr.o.setZero();
  pr.tv = Eigen::Vector3d(0, 0, 1);
  pr.th = Eigen::Vector3d(0, 1, 0);
  pr.c_h = 0.0;
  pr.c_v = 0.3;
  pr.l_c = 0.3;
  const Eigen::Vector3d c(0.01, 0.0, 0.3);
  pr.lever_a = 0.15 + c.dot(pr.s);
  pr.lever_b = 0.15 - c.dot(pr.s);
  const double M = 15.2064, g = 9.81;
  Eigen::Vector3d f[2];
  MdlAMB::stanceForces(Eigen::Vector3d(0, 0, M * g), pr, f);
  std::cout << "  f_FL = " << f[0].transpose() << ", f_RR = " << f[1].transpose() << std::endl;
  T_CHECK(std::abs(f[0](2) * 0.14 - f[1](2) * 0.16) < 1e-9);
  T_CHECK(std::abs(f[0](2) + f[1](2) - M * g) < 1e-9);
  T_CHECK(f[0].head<2>().norm() < 1e-12 && f[1].head<2>().norm() < 1e-12);
  std::cout << "  PASS" << std::endl;
}

